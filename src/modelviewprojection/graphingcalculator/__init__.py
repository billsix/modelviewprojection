"""Graphing-calculator programs: short runners over gacalc's graphers.

Two standalone, run-by-path programs that plot first-class Python functions
the way a graphing calculator does -- ``grapher2d`` for ``f(x)`` and
``grapher3d`` for an ``f(x, y)`` surface.  Each holds only its list of
functions, authored in source; the window, view and drawing are
``gacalc.gl.grapher2d.run`` and ``gacalc.gl.grapher3d.run``
(github.com/billsix/geometricalgebra)."""
